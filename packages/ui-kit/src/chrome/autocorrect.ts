/** The list in force: the built-in entries the user kept, then the user's own. */
export function autoCorrectEntries(
  added: readonly (readonly [string, string])[],
  removed: readonly string[],
): { from: string; to: string }[] {
  const out = new Map<string, string>();
  for (const [from, to] of AUTOCORRECT_BUILTIN) if (!removed.includes(from) && from !== to) out.set(from, to);
  for (const [from, to] of added) if (from.trim()) out.set(from.trim(), to);
  return [...out].map(([from, to]) => ({ from, to }));
}
