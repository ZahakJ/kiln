/** The synonym sets merged into every interface language. */
const SYNONYM_SETS: readonly Readonly<Record<string, readonly string[]>>[] = [ENGLISH, GERMAN, ARABIC];

/**
 * Office terminology and everyday phrasings people type into "Tell me" / the command palette
 *. Keys are command ids; values are extra search terms. English, German and Arabic
 * Office names are all included whatever the interface language, so someone who learnt Office in
 * German finds "Fenster fixieren" in an English Kiln, and the reverse.
 */
export function createOfficeSynonyms(): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const set of SYNONYM_SETS) {
    for (const [id, terms] of Object.entries(set)) out[id] = [...(out[id] ?? []), ...terms];
  }
  return out;
}
