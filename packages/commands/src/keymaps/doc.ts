/** docs/SHORTCUTS.md as generated from the table and keymaps of this directory. */
import { formatChord, parseShortcut } from '../keys.ts';
import keyTips from '../keytips-audit.json' with { type: 'json' };
import { type KeyTipsAudit, renderShortcutsDoc } from '../shortcutsDoc.ts';
import { commonKeymap } from './common.ts';
import { deckKeymap } from './deck.ts';
import { gridKeymap } from './grid.ts';
import { SHORTCUT_TABLE, SLIDE_SHOW_TABLE } from './table.ts';
import { writeKeymap } from './write.ts';

/** Display label of a keymap key on Windows/Linux (`Mod+Shift+L` → `Ctrl+Shift+L`). */
function label(key: string): string {
  return formatChord(parseShortcut(key, 'other'), 'other');
}

export function shortcutsDocText(): string {
  return renderShortcutsDoc({
    rows: SHORTCUT_TABLE,
    slideShow: SLIDE_SHOW_TABLE,
    layers: { common: commonKeymap, write: writeKeymap, grid: gridKeymap, deck: deckKeymap },
    label,
    keyTips: keyTips as unknown as KeyTipsAudit,
  });
}

/** docs/manual/shortcuts.md: the same tables for readers, without the command ids behind them. */
export function manualShortcutsText(): string {
  const doc = shortcutsDocText();
  const from = (heading: string) => doc.indexOf(heading);
  const table = doc.slice(from('| Shortcut |'), from('## Commands behind each shortcut'));
  const keyTips = doc.slice(from('## Key Tips'));
  return [
    '# Keyboard shortcuts\n\n',
    '<!-- Generated by `pnpm --filter @kiln/commands shortcuts:doc` from packages/commands/src/keymaps/. Do not edit by hand. -->\n\n',
    `This table lists Office's common shortcuts as Kiln binds them, in ${SHORTCUT_TABLE.length} rows, and the keys of a slide show. `,
    'Shortcuts marked ★ are Kiln additions that Office does not have; a dash means the shortcut does nothing in that app. ',
    "End-to-end tests send each row's keys to each app as a keydown event and check the command it reaches, in a development build.\n\n",
    'In the application, **Ctrl+/** ★ shows the shortcuts for the current app, and **File ▸ Options ▸ Keyboard** lists and remaps them.\n\n',
    table,
    keyTips,
  ].join('');
}
