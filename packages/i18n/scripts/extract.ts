/**
 * Builds the English locale (`locales/en.json`) from the sources:
 *
 * - every `t('…')`, `tOr('key', '…')` and `msg('…')` with a literal key in the interface sources;
 * - the command system's messages (`@kiln/commands` `commandMessages`: command titles as
 *   `cmd.<id>`, descriptions, ribbon labels).
 *
 * A key that is English text is its own message. A structured key (`grid.status.cells`, used for
 * ICU plurals) keeps the English message written for it in `en.json`.
 *
 *   pnpm --filter @kiln/i18n extract          rewrite locales/en.json
 *   pnpm --filter @kiln/i18n extract:check    exit 1 when en.json is out of date (CI, unit test)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { commandMessages } from '../../commands/src/messages.ts';
import { collectMessages, ROOT, read, sourceFiles } from './scan.ts';

export const HEADER =
  'Kiln interface messages, English (the source locale). Generated by `pnpm --filter @kiln/i18n extract` from the t()/msg() calls of the interface and the command catalog; edit the sources, not this file (structured keys such as grid.status.cells keep the English written here). Keys: cmd.<command id> is a command title, cmd.<id>.description its ScreenTip; any other key is the English text itself. Messages use ICU syntax.';

/** A key that names a message instead of spelling it (`grid.status.cells`). */
export function isStructuredKey(key: string): boolean {
  return /^[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9_-]+)+$/.test(key);
}

export const EN_PATH = join(ROOT, 'packages/i18n/locales/en.json');

export interface Extraction {
  messages: Record<string, string>;
  /** Keys used in code with no English message (structured keys missing from en.json). */
  undefinedKeys: { key: string; where: string }[];
}

export function extract(existing: Record<string, string>): Extraction {
  const found = new Map<string, string>();
  const undefinedKeys: { key: string; where: string }[] = [];
  for (const [k, v] of Object.entries(commandMessages())) found.set(k, v);
  for (const file of sourceFiles()) {
    for (const use of collectMessages(file, read(file))) {
      if (found.has(use.key)) continue;
      if (use.fallback !== undefined) found.set(use.key, use.fallback);
      else if (isStructuredKey(use.key)) {
        const en = existing[use.key];
        if (en === undefined) undefinedKeys.push({ key: use.key, where: `${file}:${use.line}` });
        else found.set(use.key, en);
      } else found.set(use.key, use.key);
    }
  }
  const messages: Record<string, string> = { '//': HEADER };
  for (const k of [...found.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))) {
    messages[k] = found.get(k) as string;
  }
  return { messages, undefinedKeys };
}

export function readJson(path: string): Record<string, string> {
  return JSON.parse(readFileSync(path, 'utf8')) as Record<string, string>;
}

export function serialize(messages: Record<string, string>): string {
  return `${JSON.stringify(messages, null, 2)}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const existing = readJson(EN_PATH);
  const { messages, undefinedKeys } = extract(existing);
  for (const u of undefinedKeys) console.error(`no English message for "${u.key}" (${u.where})`);
  const text = serialize(messages);
  const before = readFileSync(EN_PATH, 'utf8');
  if (process.argv.includes('--check')) {
    if (text !== before || undefinedKeys.length) {
      const old = new Set(Object.keys(existing));
      const now = new Set(Object.keys(messages));
      const added = [...now].filter((k) => !old.has(k));
      const removed = [...old].filter((k) => !now.has(k));
      for (const k of added.slice(0, 40)) console.error(`+ ${k}`);
      for (const k of removed.slice(0, 40)) console.error(`- ${k}`);
      console.error('locales/en.json is out of date: run `pnpm --filter @kiln/i18n extract`');
      process.exit(1);
    }
    console.log(`locales/en.json is up to date (${Object.keys(messages).length - 1} messages)`);
  } else {
    writeFileSync(EN_PATH, text);
    console.log(`wrote locales/en.json (${Object.keys(messages).length - 1} messages)`);
  }
}
