/**
 * `pnpm fidelity --format docx`: round-trips every .docx feature fixture (read → write → read), scores
 * structure, text, LibreOffice rendering and whether LibreOffice opens the rewritten file (PLAN §5),
 * prints the table, writes the docx section of `docs/qa/fidelity.md` and exits non-zero when a feature
 * fixture misses the §3.5 targets.
 *
 * Options: `--format <docx|xlsx|pptx>` (this script only handles docx; other formats are ignored),
 * `--external` to add the downloaded real-world corpus (reported, not enforced), `--no-visual` to skip
 * LibreOffice rendering, `--no-write` to leave the report file alone.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  type FidelityScore,
  formatScoreTable,
  listFixtures,
  REPO_ROOT,
  sofficeAvailable,
} from '@kiln/testing';
import { THRESHOLDS } from './fidelity-thresholds.ts';
import { featureFixtures, rewriteAll, scoreCorpus } from './model.ts';

function meetsTargets(s: FidelityScore): boolean {
  return (
    s.structural >= THRESHOLDS.structural &&
    s.text >= THRESHOLDS.text &&
    s.oracle_opens !== false &&
    (s.visual === null || s.visual >= THRESHOLDS.visual)
  );
}

const args = process.argv.slice(2);
const formatArg = args.indexOf('--format');
const format = formatArg >= 0 ? args[formatArg + 1] : undefined;

async function main(): Promise<number> {
  if (format && format !== 'docx') return 0;
  const visual = !args.includes('--no-visual');
  const started = Date.now();
  const features = await scoreCorpus(rewriteAll(featureFixtures()), { visual });
  const externalPaths = args.includes('--external') ? listFixtures('docx', 'external') : [];
  const external = externalPaths.length ? await scoreCorpus(rewriteAll(externalPaths), { visual }) : [];
  const seconds = ((Date.now() - started) / 1000).toFixed(0);

  const failing = features.filter((s) => !meetsTargets(s));
  const table = formatScoreTable(features);
  console.log(`\nDOCX round-trip fidelity (${features.length} feature fixtures, ${seconds} s)\n`);
  console.log(table);
  if (external.length) {
    console.log(`\nExternal corpus (${external.length} files, informational)\n`);
    console.log(formatScoreTable(external));
  }
  if (!sofficeAvailable())
    console.log('\nLibreOffice is not installed: visual and oracle_opens were not measured.');
  console.log(
    failing.length
      ? `\n${failing.length} fixture(s) below target: ${failing.map((s) => s.file).join(', ')}`
      : `\nAll ${features.length} feature fixtures meet the targets (structural ≥ ${THRESHOLDS.structural}, text = 1.00, LibreOffice opens, visual ≥ ${THRESHOLDS.visual}).`,
  );

  if (!args.includes('--no-write')) writeReport(features, external);
  return failing.length ? 1 : 0;
}

const START = '<!-- fidelity:docx:start -->';
const END = '<!-- fidelity:docx:end -->';

function writeReport(features: FidelityScore[], external: FidelityScore[]): void {
  const path = join(REPO_ROOT, 'docs', 'qa', 'fidelity.md');
  const mean = (k: 'structural' | 'text' | 'visual') => {
    const v = features.map((s) => s[k]).filter((x): x is number => typeof x === 'number');
    return v.length ? (v.reduce((a, b) => a + b, 0) / v.length).toFixed(3) : '—';
  };
  const section = [
    START,
    '## DOCX (Kiln Write)',
    '',
    `Generated by \`pnpm fidelity --format docx\` on ${new Date().toISOString().slice(0, 10)}: every`,
    '`packages/testing/fixtures/docx/features/*.docx` file is read, written with `writeDocx` and read again.',
    'Structural = fraction of `readDocx` model leaves (document tree, styles, numbering, settings, sections,',
    'comments, media, preserved parts, warnings) unchanged, identifiers ignored; text = package text equality;',
    'visual = LibreOffice renderings of the original and the rewritten file compared page by page at 60 dpi;',
    'LibreOffice opens = the rewritten file converts to PDF. Targets (PLAN §3.5): structural ≥ 0.95, text 1.00,',
    'visual ≥ 0.90, opens.',
    '',
    `Means: structural ${mean('structural')}, text ${mean('text')}, visual ${mean('visual')}.`,
    '',
    formatScoreTable(features),
    ...(external.length
      ? [
          '',
          `Real-world corpus (\`tools/fetch-corpus.sh\`, ${external.length} files, informational):`,
          '',
          formatScoreTable(external),
        ]
      : []),
    '',
    'What a save changes on purpose (excluded from the structural model): `dcterms:modified`, the',
    '`cp:revision` count, `docProps/app.xml` (Application "Kiln", recomputed statistics) and the',
    "namespace declarations of the document root. Inline pictures are written with Word's explicit zero",
    'text distances, which LibreOffice draws slightly tighter than files that omit them (images-inline).',
    END,
  ].join('\n');
  let doc = existsSync(path)
    ? readFileSync(path, 'utf8')
    : '# Round-trip fidelity\n\nScores of the Office file round trips (PLAN §5), one section per format, written by `pnpm fidelity`.\n';
  if (doc.includes(START) && doc.includes(END)) {
    doc = doc.slice(0, doc.indexOf(START)) + section + doc.slice(doc.indexOf(END) + END.length);
  } else doc = `${doc.trimEnd()}\n\n${section}\n`;
  writeFileSync(path, doc);
  console.log(`\nWrote ${path}`);
}

main().then(
  (code) => {
    process.exitCode = code;
  },
  (e) => {
    console.error(e);
    process.exitCode = 1;
  },
);
