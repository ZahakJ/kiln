/**
 * Transcribes ECMA-376 Part 1 presetShapeDefinitions.xml into `src/drawingml/presets/*.ts`.
 *
 *   pnpm --filter @kiln-ref/ooxml gen:presets [path/to/presetShapeDefinitions.xml]
 *
 * Without a path the file is downloaded from the LibreOffice source tree, which carries the unmodified
 * ECMA-376 annex file. Output is grouped by category and formatted with Biome.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGeometry } from '../src/drawingml/geometry.ts';
import { parseXml } from '../src/xml/parse.ts';

const SOURCE_URL =
  'https://raw.githubusercontent.com/LibreOffice/core/master/oox/source/drawingml/customshapes/presetShapeDefinitions.xml';
const outDir = join(dirname(fileURLToPath(import.meta.url)), '../src/drawingml/presets');

async function load(): Promise<string> {
  const p = process.argv[2];
  if (p) return readFileSync(p, 'utf8');
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  return res.text();
}

function category(name: string): string {
  if (/^actionButton/.test(name)) return 'action-buttons';
  if (/^flowChart/.test(name)) return 'flowchart';
  if (/Callout|^callout|^borderCallout|^accent/.test(name)) return 'callouts';
  if (/Connector|^line$|^lineInv$/.test(name)) return 'lines-connectors';
  if (/Arrow|^chevron$|^homePlate$/.test(name)) return 'arrows';
  if (/^math/.test(name)) return 'math';
  if (/^star|Seal|[Rr]ibbon|[Ss]croll|^wave$|^doubleWave$/.test(name)) return 'stars-banners';
  return 'basic';
}

const camel = (s: string) => s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

const xml = await load();
const root = parseXml(xml, { normalizePrefixes: false }).root;
const groups = new Map<string, [string, unknown][]>();
let count = 0;
for (const shape of root.children) {
  if (shape.type !== 'element') continue;
  // The annex file declares the DrawingML namespace as the default on each child list; re-prefix so the
  // geometry parser (which expects `a:` names) can read it.
  const prefixed = JSON.parse(JSON.stringify(shape));
  const fix = (n: { type: string; name?: string; children?: unknown[] }) => {
    if (n.type !== 'element') return;
    if (n.name && !n.name.includes(':')) n.name = `a:${n.name}`;
    for (const c of n.children ?? []) fix(c as never);
  };
  for (const c of prefixed.children) fix(c);
  const def = parseGeometry(prefixed);
  const cat = category(shape.name);
  if (!groups.has(cat)) groups.set(cat, []);
  groups.get(cat)?.push([shape.name, def]);
  count++;
}
if (count !== 187) throw new Error(`expected 187 presets, found ${count}`);

const header = (cat: string) =>
  `// Generated by scripts/gen-presets.ts from ECMA-376 Part 1 presetShapeDefinitions.xml. Do not edit.\n` +
  `// Category: ${cat}.\nimport type { GeometryDef } from '../geometry.ts';\n\n`;
const files: string[] = [];
for (const [cat, list] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  list.sort(([a], [b]) => a.localeCompare(b));
  const body = list.map(([n, d]) => `  ${n}: ${JSON.stringify(d)},`).join('\n');
  const file = join(outDir, `${cat}.ts`);
  writeFileSync(
    file,
    `${header(cat)}export const ${camel(cat)}: Record<string, GeometryDef> = {\n${body}\n};\n`,
  );
  files.push(file);
  console.log(`${cat}: ${list.length}`);
}
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', ...files], { stdio: 'inherit' });
