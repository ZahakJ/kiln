//! Generation of everything the TypeScript side derives from this crate (feature `schema`).
//!
//! * [`typescript_files`]: one `.ts` declaration file per type (ts-rs) plus `index.ts`;
//! * [`catalog_json`]: every `CommandMeta` as `catalog.json`;
//! * [`schema_json`]: the serde data model of every type (traced with `serde-reflection`), which
//!   drives the TypeScript postcard decoder;
//! * [`vectors`]: postcard test vectors (`<Type>.bin`) with their JSON form (`<Type>.json`).
//!
//! All output is deterministic, so `cargo xtask protocol --check` can compare it byte for byte.

use std::collections::BTreeMap;

use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_reflection::{Format, Registry, Tracer, TracerConfig};
use ts_rs::TS;

use crate::samples::Samples;

/// The first line of every generated TypeScript file.
pub const TS_BANNER: &str =
    "// generated by `cargo xtask protocol` from crates/kiln-protocol, do not edit\n";

/// The value of the `"//"` key of every generated JSON file.
pub const JSON_BANNER: &str =
    "generated by `cargo xtask protocol` from crates/kiln-protocol, do not edit";

/// A type that crosses the bridge.
pub trait ProtocolType: Serialize + DeserializeOwned + TS + Samples + 'static {}
impl<T: Serialize + DeserializeOwned + TS + Samples + 'static> ProtocolType for T {}

/// Receives every protocol type.
pub trait Visitor {
    /// Called once per type. `traceable` is false for types whose deserialisation cannot be traced
    /// because they contain an enum without variants (`Command` while an app has no commands);
    /// their schema comes from the samples alone.
    fn visit<T: ProtocolType>(&mut self, name: &'static str, traceable: bool);
}

macro_rules! visit_types {
    ($v:ident; $($ty:ty),* $(,)?) => {
        $( $v.visit::<$ty>(stringify!($ty), true); )*
    };
}

/// Visits every protocol type, in a stable order.
pub fn visit_all(v: &mut impl Visitor) {
    use crate::*;
    // Contains `GridCommand`, `DeckCommand` and `NotesCommand`, which have no variants yet.
    v.visit::<Command>("Command", false);
    visit_types!(v;
        SuiteCommand, WriteCommand, CaretMotion, SelectUnit, CommandInfo, Tier, Availability,
        App, DocKind, FileFormat, OpenHint,
        geom::Point, geom::Size, geom::Rect,
        ViewMode, Viewport,
        TextPos, CellAddr, CellRange, SelKind, Caret, HandleKind, Compass, Handle, Selection,
        Position, CellStats, StatusBar, DocSummary,
        Query, ParagraphText, QueryResult, CompatSeverity, CompatOrigin, CompatIssue,
        ErrorKind, ErrorInfo,
        RequestId, FileFilter, RecentFile, HostOp, HostRequest, HostReply,
        Outcome, CoreInfo, ExecValue, ExecResult,
        A11yRole, A11yNode, A11yTree,
        Progress, RecoveryEntry, Event,
        DocId, NodeId,
    );
    // WP-54: the display list (kiln-scene), including SceneDelta.
    crate::scene::samples::visit(v);
}

/// The ts-rs configuration: 64-bit integers are JavaScript numbers (ids and revisions stay below
/// 2^53 by construction; the decoder rejects larger values).
fn ts_config() -> ts_rs::Config {
    ts_rs::Config::new().with_large_int("number")
}

/// Every generated TypeScript file, keyed by file name (`Command.ts`, …, `index.ts`).
///
/// # Errors
///
/// Fails when ts-rs cannot render a type.
pub fn typescript_files() -> Result<BTreeMap<String, String>, String> {
    struct Collect {
        cfg: ts_rs::Config,
        files: BTreeMap<String, String>,
        error: Option<String>,
    }
    impl Collect {
        fn add<T: TS + ?Sized + 'static>(&mut self) {
            let Some(path) = T::output_path() else {
                return;
            };
            let name = path.to_string_lossy().into_owned();
            if self.files.contains_key(&name) || self.error.is_some() {
                return;
            }
            match T::export_to_string(&self.cfg) {
                Ok(text) => {
                    self.files.insert(name, with_banner(&text));
                    T::visit_dependencies(self);
                }
                Err(e) => self.error = Some(format!("{}: {e}", std::any::type_name::<T>())),
            }
        }
    }
    impl ts_rs::TypeVisitor for Collect {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            self.add::<T>();
        }
    }
    impl Visitor for Collect {
        fn visit<T: ProtocolType>(&mut self, _: &'static str, _: bool) {
            self.add::<T>();
        }
    }

    let mut c = Collect {
        cfg: ts_config(),
        files: BTreeMap::new(),
        error: None,
    };
    visit_all(&mut c);
    if let Some(e) = c.error {
        return Err(e);
    }
    let mut index = String::from(TS_BANNER);
    index.push_str("// Every type of the Rust↔TypeScript protocol (kiln-protocol).\n\n");
    for name in c.files.keys() {
        let stem = name.trim_end_matches(".ts");
        index.push_str(&format!("export type {{ {stem} }} from './{stem}';\n"));
    }
    index.push_str(&format!(
        "\n/** The wire protocol version this package was generated for (`kiln_protocol::PROTOCOL_VERSION`). */\nexport const PROTOCOL_VERSION = {};\n",
        crate::PROTOCOL_VERSION
    ));
    c.files.insert("index.ts".into(), index);
    Ok(c.files)
}

/// Replaces ts-rs's own header line with ours.
fn with_banner(text: &str) -> String {
    let body = match text.split_once('\n') {
        Some((first, rest)) if first.starts_with("// This file was generated by [ts-rs]") => rest,
        _ => text,
    };
    format!("{TS_BANNER}{body}")
}

/// `catalog.json`: the banner, the protocol version and every command row.
///
/// # Errors
///
/// Never in practice; serialisation errors are reported as text.
pub fn catalog_json() -> Result<String, String> {
    #[derive(Serialize)]
    struct Catalog {
        #[serde(rename = "//")]
        banner: &'static str,
        protocol: u32,
        commands: Vec<crate::CommandInfo>,
    }
    let doc = Catalog {
        banner: JSON_BANNER,
        protocol: crate::PROTOCOL_VERSION,
        commands: crate::catalog(),
    };
    to_json(&doc)
}

fn to_json<T: Serialize>(value: &T) -> Result<String, String> {
    serde_json::to_string_pretty(value)
        .map(|mut s| {
            s.push('\n');
            s
        })
        .map_err(|e| e.to_string())
}

/// The traced serde data model of every protocol type.
///
/// # Errors
///
/// Fails when tracing fails or an enum's variants could not all be discovered.
pub fn registry() -> Result<Registry, String> {
    let mut run = Trace::new();
    visit_all(&mut run);
    run.finish().map(|(registry, _)| registry)
}

/// `schema.json`: the banner and the registry.
///
/// # Errors
///
/// See [`registry`].
pub fn schema_json() -> Result<String, String> {
    #[derive(Serialize)]
    struct Schema {
        #[serde(rename = "//")]
        banner: &'static str,
        protocol: u32,
        types: Registry,
    }
    to_json(&Schema {
        banner: JSON_BANNER,
        protocol: crate::PROTOCOL_VERSION,
        types: registry()?,
    })
}

/// One test vector: `values` encoded with postcard as a `Vec<T>`, and the same values as JSON.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Vector {
    /// The type name (file stem).
    pub name: &'static str,
    /// `<name>.bin`: postcard encoding of the value list.
    pub postcard: Vec<u8>,
    /// `<name>.json`: `{"type", "format", "values"}`.
    pub json: String,
}

/// Every test vector, in [`visit_all`] order.
///
/// # Errors
///
/// See [`registry`]; also fails if a value cannot be encoded.
pub fn vectors() -> Result<Vec<Vector>, String> {
    let mut run = Trace::new();
    visit_all(&mut run);
    run.finish().map(|(_, vectors)| vectors)
}

/// Tracing pass shared by [`registry`] and [`vectors`].
struct Trace {
    tracer: Tracer,
    samples: serde_reflection::Samples,
    vectors: Vec<Vector>,
    error: Option<String>,
}

impl Trace {
    fn new() -> Self {
        Self {
            tracer: Tracer::new(TracerConfig::default()),
            samples: serde_reflection::Samples::new(),
            vectors: Vec::new(),
            error: None,
        }
    }

    fn finish(self) -> Result<(Registry, Vec<Vector>), String> {
        if let Some(e) = self.error {
            return Err(e);
        }
        let registry = self.tracer.registry().map_err(|e| e.to_string())?;
        Ok((registry, self.vectors))
    }

    fn vector<T: ProtocolType>(
        &mut self,
        name: &'static str,
        traceable: bool,
    ) -> Result<(), String> {
        let mut values = T::samples();
        if values.is_empty() {
            return Err(format!("{name}: no samples"));
        }
        let mut format = None;
        for v in &values {
            let (f, _) = self
                .tracer
                .trace_value(&mut self.samples, v)
                .map_err(|e| format!("{name}: {e}"))?;
            format = Some(f);
        }
        if traceable {
            // Deserialisation tracing discovers every variant, including ones the samples miss,
            // and yields one value per variant, which are added to the vectors.
            let (f, traced) = self
                .tracer
                .trace_type::<T>(&self.samples)
                .map_err(|e| format!("{name}: {e}"))?;
            format = Some(f);
            values.extend(traced);
        }
        let format: Format = format.ok_or_else(|| format!("{name}: no format"))?;
        let postcard = postcard::to_allocvec(&values).map_err(|e| format!("{name}: {e}"))?;
        #[derive(Serialize)]
        struct File<'a, T> {
            #[serde(rename = "type")]
            ty: &'a str,
            format: &'a Format,
            values: &'a [T],
        }
        let json = to_json(&File {
            ty: name,
            format: &format,
            values: &values,
        })?;
        self.vectors.push(Vector {
            name,
            postcard,
            json,
        });
        Ok(())
    }
}

impl Visitor for Trace {
    fn visit<T: ProtocolType>(&mut self, name: &'static str, traceable: bool) {
        if self.error.is_none() {
            // Strip the module path of `geom::Point`.
            let short = name.rsplit("::").next().unwrap_or(name);
            let short: &'static str = match short {
                n if n == name => name,
                _ => &name[name.len() - short.len()..],
            };
            if let Err(e) = self.vector::<T>(short, traceable) {
                self.error = Some(e);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_type_has_a_typescript_file() {
        let files = typescript_files().expect("export");
        for name in [
            "Command.ts",
            "Event.ts",
            "Viewport.ts",
            "GridCommand.ts",
            "index.ts",
            "DocId.ts",
        ] {
            assert!(files.contains_key(name), "{name} missing");
        }
        for (name, text) in &files {
            assert!(text.starts_with(TS_BANNER), "{name} lacks the banner");
            assert!(!text.contains("bigint"), "{name} uses bigint");
        }
        assert!(files["GridCommand.ts"].contains("never"));
        assert!(files["index.ts"].contains("export const PROTOCOL_VERSION = 1;"));
        assert!(files["Command.ts"].contains("\"Suite\": SuiteCommand"));
    }

    #[test]
    fn catalog_and_schema_are_json_with_banners() {
        let catalog: serde_json::Value = serde_json::from_str(&catalog_json().unwrap()).unwrap();
        assert_eq!(catalog["//"], JSON_BANNER);
        assert!(
            catalog["commands"]
                .as_array()
                .is_some_and(|c| c.len() >= 15)
        );
        let schema: serde_json::Value = serde_json::from_str(&schema_json().unwrap()).unwrap();
        assert!(schema["types"]["Command"].is_object());
        assert!(schema["types"]["Event"].is_object());
    }

    #[test]
    fn vectors_cover_every_type_and_every_variant() {
        let vectors = vectors().expect("vectors");
        let names: Vec<&str> = vectors.iter().map(|v| v.name).collect();
        assert!(names.contains(&"Point") && names.contains(&"Event") && names.contains(&"Command"));
        let mut unique = names.clone();
        unique.sort_unstable();
        unique.dedup();
        assert_eq!(unique.len(), names.len(), "duplicate vector names");
        // Every variant of every traced enum appears in its vector (serde-reflection added the
        // missing ones); spot-check Event, whose samples list all variants anyway.
        let event = vectors.iter().find(|v| v.name == "Event").unwrap();
        let parsed: serde_json::Value = serde_json::from_str(&event.json).unwrap();
        assert!(parsed["values"].as_array().unwrap().len() >= 10);
    }

    /// The committed vectors are what the code generates, and every `.bin` decodes (postcard) to
    /// the values in its `.json`.
    #[test]
    fn committed_vectors_are_current_and_decode() {
        struct Check {
            dir: std::path::PathBuf,
            checked: usize,
        }
        impl Visitor for Check {
            fn visit<T: ProtocolType>(&mut self, name: &'static str, _: bool) {
                let short = name.rsplit("::").next().unwrap_or(name);
                let bin = std::fs::read(self.dir.join(format!("{short}.bin")))
                    .unwrap_or_else(|e| panic!("{short}.bin: {e} (run `cargo xtask protocol`)"));
                let json: serde_json::Value = serde_json::from_slice(
                    &std::fs::read(self.dir.join(format!("{short}.json"))).unwrap(),
                )
                .unwrap();
                let decoded: Vec<T> = postcard::from_bytes(&bin)
                    .unwrap_or_else(|e| panic!("{short}.bin does not decode: {e}"));
                // Through text, so `f32`s print in their shortest form as in the file.
                let reencoded: serde_json::Value =
                    serde_json::from_str(&serde_json::to_string(&decoded).unwrap()).unwrap();
                assert_eq!(
                    reencoded, json["values"],
                    "{short}: postcard and JSON disagree"
                );
                self.checked += 1;
            }
        }
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/vectors");
        for v in vectors().unwrap() {
            let on_disk = std::fs::read(dir.join(format!("{}.bin", v.name))).unwrap_or_default();
            assert!(
                on_disk == v.postcard,
                "{}.bin is stale: run `cargo xtask protocol`",
                v.name
            );
            let json =
                std::fs::read_to_string(dir.join(format!("{}.json", v.name))).unwrap_or_default();
            assert!(
                json == v.json,
                "{}.json is stale: run `cargo xtask protocol`",
                v.name
            );
        }
        let mut check = Check { dir, checked: 0 };
        visit_all(&mut check);
        assert!(check.checked >= 50);
    }
}
